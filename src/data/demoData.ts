type DemoIdeaSeed = Omit<
  TradingIdea,
  | 'sma10' | 'sma20' | 'aboveSma10' | 'aboveSma20' | 'priorRunPct' | 'tightDays'
  | 'baseLengthDays' | 'dollarVolume' | 'kyleScore' | 'characteristics' | 'setupStage'
>

function enrichKyleDemo(idea: DemoIdeaSeed): TradingIdea {
  const aboveSma10 = idea.aboveSma50 && idea.pctFrom52wHigh >= -12
  const aboveSma20 = idea.aboveSma50
  const priorRunPct = Math.max(idea.perf3M, idea.perf1M * 1.5)
  const tightDays = idea.adrPct <= 4 ? 9 : idea.adrPct <= 5.5 ? 6 : 3
  const baseLengthDays = idea.setupType === 'Range Breakout' ? Math.max(8, tightDays) : Math.max(3, tightDays - 2)
  const isAPlus = idea.isAPlus
  const kyleScore = kyleScoreHeuristic({
    aboveSma200: idea.aboveSma200,
    aboveSma50: idea.aboveSma50,
    aboveSma10,
    aboveSma20,
    pctFrom52wHigh: idea.pctFrom52wHigh,
    rvol: idea.rvol,
    adrPct: idea.adrPct,
    priorRunPct,
    isAPlus,
  })
  const characteristics: CharacteristicTag[] = deriveCharacteristics({
    aboveSma10,
    aboveSma20,
    aboveSma50: idea.aboveSma50,
    aboveSma200: idea.aboveSma200,
    pctFrom52wHigh: idea.pctFrom52wHigh,
    catalyst: idea.catalyst,
  })
  const priorRounded = Math.round(priorRunPct * 10) / 10
  const setupStage =
    setupStageHeuristic({
      aboveSma200: idea.aboveSma200,
      aboveSma10,
      aboveSma20,
      pctFrom52wHigh: idea.pctFrom52wHigh,
      tightDays,
      rvol: idea.rvol,
      dayPct: idea.dayPct,
      priorRunPct: priorRounded,
    }) ?? 'watching'
  return {
    ...idea,
    sma10: Math.round(idea.price * 0.98 * 100) / 100,
    sma20: Math.round(idea.price * 0.96 * 100) / 100,
    aboveSma10,
    aboveSma20,
    priorRunPct: priorRounded,
    tightDays,
    baseLengthDays,
    dollarVolume: idea.avgDollarVol,
    kyleScore,
    characteristics,
    setupStage,
  }
}

